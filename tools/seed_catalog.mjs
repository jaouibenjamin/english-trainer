// The catalogue of what can earn points (docs/BACKEND.md section 5), generated from the game's own content files.
//   node tools/seed_catalog.mjs            writes supabase/seed/catalog.sql
//   node tools/seed_catalog.mjs --stdout   prints it (tests/catalog_check.py compares the two: a stale seed fails)
// The keys are exactly what js/api.js events() sends: an English word (S.st), an island level ("1-sling", S.g.st),
// a Fraction Bay level ("2-pizza", S.m.st), a text id (S.read) and the mock exam paper. Safe to run twice: rows are
// added, never removed (a key that disappears from the game keeps its history), and a level's size is updated.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ISLANDS, levelKey, TEXTS, WORDS } from "../js/data.js";
import { M_ISLANDS } from "../js/mdata.js";
import { XPLAN } from "../js/xdata.js";

const q = (s) => "'" + String(s).replaceAll("'", "''") + "'";
const items = new Map();                      // a word in two parts (July: birthdays and months) is one item
for (const w of WORDS) if (!items.has(w.en)) items.set(w.en, "part-" + w.p);
const levels = [];
for (const i of ISLANDS) for (const [type] of i.levels) levels.push(["en", levelKey(i.id, type), 0]);
for (const i of M_ISLANDS) for (const t of i.levels) levels.push(["math", i.id + "-" + t, 0]);
for (const t of TEXTS) levels.push(["read", String(t.id), t.qs.length]);
levels.push(["exam", "mock", Object.values(XPLAN).reduce((a, b) => a + b, 0)]);

for (const [k] of items) if (k.length > 64 || /[\u0000-\u001f]/.test(k)) throw new Error("item key the database refuses: " + k);
for (const [, k] of levels) if (k.length > 60 || /[\u0000-\u001f]/.test(k)) throw new Error("level key the database refuses: " + k);

const sql = `-- GENERATED by tools/seed_catalog.mjs from js/data.js, js/mdata.js and js/xdata.js. Do not edit by hand:
-- change the content, run \`node tools/seed_catalog.mjs\`, commit both. tests/catalog_check.py fails when this is stale.
-- Load after the migrations (docs/BACKEND.md section 9, step 12). Safe to run again.
insert into public.items (game, item_key, skill) values
${[...items].map(([k, s]) => `  ('en', ${q(k)}, ${q(s)})`).join(",\n")}
on conflict (game, item_key) do nothing;
insert into public.levels (game, level_key, size) values
${levels.map(([g, k, n]) => `  (${q(g)}, ${q(k)}, ${n})`).join(",\n")}
on conflict (game, level_key) do update set size = excluded.size;
-- ${items.size} items, ${levels.length} levels, texts and papers
`;
if (process.argv.includes("--stdout")) process.stdout.write(sql);
else {
  const out = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase", "seed", "catalog.sql");
  writeFileSync(out, sql);
  console.log(`wrote supabase/seed/catalog.sql: ${items.size} items, ${levels.length} levels, texts and papers`);
}
