#!/usr/bin/env python3
"""Writes js/voice.js from the generation log (text -> {job_id, status, url}) for the texts in tests/voice_texts.json.
   Run: python3 tests/voice_map.py /path/to/voice_jobs.json"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
log = json.load(open(sys.argv[1], encoding='utf-8'))
texts = [x['text'] for x in json.load(open(os.path.join(ROOT, 'tests', 'voice_texts.json'), encoding='utf-8'))]
urls = {t: log[t]['url'] for t in texts if log.get(t, {}).get('url')}
base = os.path.commonprefix(list(urls.values())) if urls else ''
assert all(u.endswith('.wav') for u in urls.values())
rows = ',\n'.join(json.dumps([t, u[len(base):-4]], ensure_ascii=False, separators=(',', ':')) for t, u in urls.items())
out = f"""/* The recorded voice: one clip per English text the game can speak (list: tests/voice_texts.json, built by tests/voice_texts.mjs).
   Generated by tests/voice_map.py, do not edit by hand. Texts without a clip are spoken by the browser's own voice. */
const BASE={json.dumps(base)};
const C=new Map([
{rows}]);
export const norm=s=>String(s??'').trim().replace(/\\s+/g,' ');
const LOW=new Map();for(const [k,v] of C){{const l=k.toLowerCase();if(!LOW.has(l))LOW.set(l,v)}}
export const HAS_CLIPS=C.size>0;
/* exact text first (case matters: "May" the month and "may" could differ), then a lowercase match */
export function clipOf(text){{const k=norm(text),v=C.get(k)||LOW.get(k.toLowerCase());return v?BASE+v+'.wav':null}}
"""
open(os.path.join(ROOT, 'js', 'voice.js'), 'w', encoding='utf-8').write(out)
print(len(urls), 'clips,', len(texts) - len(urls), 'texts without a clip:', [t for t in texts if t not in urls][:20])
