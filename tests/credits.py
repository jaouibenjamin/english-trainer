#!/usr/bin/env python3
# suite: full=check   # picked up by tests/all.py
"""Writes assets/CREDITS.md: every file the game ships under assets/ and vendor/, what it is and where it came from.

    python3 tests/credits.py write    # rebuild assets/CREDITS.md
    python3 tests/credits.py check    # fail if it is out of date, misses a file, or names a file that is not there

Built from four lists, so it cannot drift from them:
    assets/voice/sources.tsv    the voice clips (tests/voice_local.py)
    assets/sources.tsv          the 3D models and pictures (tests/assets_local.py)
    assets/al/sources.tsv       the "Arcade Lagoon" art: kind, file, what, job, model, sha256 (no URL in it at all)
    assets/credits_extra.tsv    everything else, written by hand: section, file, what, source, sha256 (fonts and code only)
A generated file's job id is the uuid in its name: hf_<date>_<time>_<job id>. Nothing here is guessed: where an id or a
model name is not recorded, the text says so. The storage path of the account and full storage URLs are never printed.
check also verifies the sha256 of the fonts, the vendored code and the Arcade Lagoon art. Needs only python3."""
import hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'CREDITS.md')
HF = re.compile(r'hf_(\d{4})(\d{2})(\d{2})_\d{6}_([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\.[a-z0-9]+$')
NOT_RECORDED = 'not recorded'


def tsv(rel):
    lines = open(os.path.join(ROOT, rel), encoding='utf-8').read().split('\n')
    head = lines[0].split('\t')
    rows = [dict(zip(head, ln.split('\t'))) for ln in lines[1:-1]]
    if lines[-1] != '' or any(len(ln.split('\t')) != len(head) for ln in lines[1:-1]):
        raise SystemExit(f'{rel}: not a clean tab-separated list')
    return rows


def job(path):
    """(job id, date) from a generated file's name"""
    m = HF.search(path)
    if not m:
        raise SystemExit(f'{path}: no job id in the file name')
    return m.group(4), f'{m.group(1)}-{m.group(2)}-{m.group(3)}'


def cell(s):
    """text for a table cell"""
    return str(s).replace('\\', '\\\\').replace('|', '\\|').replace('`', "'").replace('<', '&lt;').replace('>', '&gt;').replace('\n', ' ')


def table(head, rows):
    return '\n'.join(['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + ['| ' + ' | '.join(r) + ' |' for r in rows]) + '\n'


def build():
    voice, assets, extra = tsv('assets/voice/sources.tsv'), tsv('assets/sources.tsv'), tsv('assets/credits_extra.tsv')
    run = open(os.path.join(ROOT, 'js', 'run.js'), encoding='utf-8').read()
    xdata = open(os.path.join(ROOT, 'js', 'xdata.js'), encoding='utf-8').read()
    look = {}                                    # file name -> the look that uses it
    for name, hero, pic in re.findall(r"\n (\w+):\{sky:.*?hero:M3D\+'([^']+)',pic:HPIC\+'([^']+)'", run, re.S):
        look[hero] = look[pic] = name
    words = re.findall(r"'([^']+)'", re.search(r'export const PIC=\[(.*?)\]', xdata, re.S).group(1))
    sheet = open(os.path.join(ROOT, 'tools', 'sheet.html'), encoding='utf-8').read()
    order = re.findall(r"'\.\./assets/(x/src/[^']+)'", sheet)       # the sheet's own order: picture i is word i
    if len(look) != 4 or sorted(set(look.values())) != ['anime', 'lowpoly']:
        raise SystemExit(f'js/run.js: expected a model and a picture for the looks anime and lowpoly, found {look}')

    def look_of(rel):
        if os.path.basename(rel) not in look:
            raise SystemExit(f'{rel}: not used by any look in js/run.js')
        return look[os.path.basename(rel)]
    sec = lambda name: [r for r in extra if r['section'] == name]
    f = lambda rel: '`' + rel + '`'
    o = []
    add = o.append

    add('# Credits\n')
    add('Everything the game ships under `assets/` and `vendor/`: what it is and where it came from. Built by\n'
        '`python3 tests/credits.py write` from `assets/voice/sources.tsv`, `assets/sources.tsv` and\n'
        '`assets/credits_extra.tsv`. Do not edit this file by hand; change the lists and build it again.\n')
    add('Voices, pictures and 3D models were generated for this game with the owner\'s own Higgsfield account. The project\'s\n'
        'rule: no known characters, brands or real people, and voices are generated presets, never clones. The job id of a\n'
        'generated file is the last part of its name (`hf_<date>_<time>_<job id>`). Where a job id or a model name is not\n'
        'recorded, it says so.\n')

    en = {}
    for r in voice:
        if r['kind'] == 'voice-en':
            en.setdefault(r['file'], []).append(r['text'])
    add(f'## English voice\n')
    add(f'{len(en)} clips for {sum(len(v) for v in en.values())} texts (a word and its capitalised form can share a clip). Tool: Higgsfield, model '
        '`seed_audio`, a generated preset voice. Each clip was cut from its original and encoded as MP3\n(`tests/voice_local.py`).\n')
    add(table(['File', 'Says', 'Made', 'Job id'], [[f('assets/voice/' + k), cell(' / '.join(v)), job(k)[1], job(k)[0]] for k, v in en.items()]))

    he = [r for r in voice if r['kind'] == 'narr-he']
    add('## Hebrew narration\n')
    add(f'{len(he)} lines spoken by Pitzi the crab in the mock exam. Tool: Higgsfield, ElevenLabs voice "Kaia", a generated preset\n'
        'voice, not a clone of anyone. The files are the originals, unchanged.\n')
    add(table(['File', 'Says', 'Made', 'Job id'], [[f('assets/voice/' + r['file']), cell(r['text']), job(r['file'])[1], job(r['file'])[0]] for r in he]))

    glb = [r for r in assets if r['kind'] == 'model-glb']
    add('## 3D runner models\n')
    add('The runners of Beach Run. Tool: Higgsfield, picture to rigged and animated 3D model; the model name is not recorded.\n')
    add(table(['File', 'What', 'Made', 'Job id', 'Changed'], [[f('assets/' + r['file']), 'runner, ' + look_of(r['file']) + ' look', job(r['file'])[1], job(r['file'])[0], cell(r['note'])] for r in glb]))

    hero = [r for r in assets if r['kind'] == 'hero-pic']
    add('## Hero pictures\n')
    add('The runner\'s picture on the Beach Run menu. Tool: Higgsfield image generation; the model name is not recorded.\n')
    add(table(['File', 'What', 'Made', 'Job id', 'Changed'], [[f('assets/' + r['file']), 'menu picture, ' + look_of(r['file']) + ' look', job(r['file'])[1], job(r['file'])[0], cell(r['note'])] for r in hero]))

    word = [r for r in assets if r['kind'] == 'word-pic']
    if len(order) != len(words) or len(set(order)) != len(order) or set(order) != {r['file'] for r in word}:
        raise SystemExit(f'tools/sheet.html draws {len(order)} pictures, js/xdata.js names {len(words)} words, assets/sources.tsv lists {len(word)} sources: they must be the same pictures')
    word_of = dict(zip(order, words))
    word.sort(key=lambda r: order.index(r['file']))
    add('## Word pictures\n')
    add('One drawing per word, in the order of the sheet. Tool: Higgsfield image generation; the model name is not recorded.\n'
        'The game shows them from one sheet, drawn from these sources by `tools/sheet.html`.\n')
    add(table(['File', 'Word', 'Made', 'Job id', 'Changed'], [[f('assets/' + r['file']), cell(w), job(r['file'])[1], job(r['file'])[0], cell(r['note'])] for r in word for w in [word_of[r['file']]]]))
    add(table(['File', 'What'], [[f(r['file']), cell(r['what'])] for r in sec('sheet')]))

    al = tsv('assets/al/sources.tsv')
    for r in al:                                 # a row may only name a file inside assets/al/
        if not re.fullmatch(r'al/[a-z]+/[a-z0-9-]+\.hf_[0-9a-f_-]+\.(webp|mp3)', r['file']) or '..' in r['file']:
            raise SystemExit(f"assets/al/sources.tsv: {r['file']!r} is not a plain file under al/")
    add('## Arcade Lagoon art (new look, not used by the live game yet)\n')
    add('Character portraits, Pitzi in the new look, backgrounds, islands, mission stones, HUD icons, and instrumental music\n'
        'and sounds. Tool: Higgsfield, model named per file. Each picture was cut, resized and encoded as WebP from its\n'
        'original; each sound was cut, levelled and encoded as mono MP3. Original work: no known characters, brands, tunes\n'
        'or real people; voices only from a generated preset (Kaia), never a clone. Two HUD icons can share one job, and the\n'
        'secret pictures come four to a job (each drawn as a sheet of four, then cut).\n')
    for name, title in (('al-avatar', 'Character portraits'), ('al-avanim', 'Character animations (2 s, played once on tap)'), ('al-pitzi', 'Pitzi'), ('al-island', 'Islands on the world map'), ('al-bg', 'Backgrounds'), ('al-ui', 'Mission stones and HUD icons'), ('al-music', 'Island themes'), ('al-sound', 'Signature sounds'), ('al-secret', 'Secret pictures for the pupil sign-in (not used yet)'), ('al-voice', 'Voice clips for the pupil sign-in (preset voice Kaia, not used yet)')):
        rows = [r for r in al if r['kind'] == name]
        for r in rows:
            if job(r['file'])[0] != r['job']:
                raise SystemExit(f"{r['file']}: the job column does not match the job id in the file name")
        add(f'### {title}\n')
        add(table(['File', 'What', 'Made', 'Job id', 'Model'], [[f('assets/' + r['file']), cell(r['what']), job(r['file'])[1], r['job'], cell(r['model'])] for r in rows]))
    if {r['kind'] for r in al} - {'al-avatar', 'al-avanim', 'al-pitzi', 'al-island', 'al-bg', 'al-ui', 'al-music', 'al-sound', 'al-secret', 'al-voice'}:
        raise SystemExit('assets/al/sources.tsv: unknown kind')

    add('## Older art: sprites, backgrounds, app icons\n')
    add('Made for this game and in the repo since its first version (2026-11-15). They are understood to have been\n'
        'generated with the owner\'s Higgsfield account and then cut and resized; the repo itself cannot confirm that. Their\n'
        'tool, model and job ids were not kept with the files, and the account\'s history available today does not list them,\n'
        f'so each is marked "{NOT_RECORDED}". Pitzi the crab is the game\'s own character.\n')
    for name, title in (('art-sp', 'Sprites'), ('art-bg', 'Backgrounds'), ('art-icons', 'App icons')):
        add(f'### {title}\n')
        add(table(['File', 'What', 'Job id'], [[f(r['file']), cell(r['what']), NOT_RECORDED] for r in sec(name)]))

    add('## Fonts\n')
    add('All under the SIL Open Font License 1.1 (the licence texts are listed with them). The files are the ones in the\n'
        'named npm package, unchanged, which are the files Google Fonts serves.\n')
    add(table(['File', 'What', 'Source: npm package and file', 'sha256'], [[f(r['file']), cell(r['what']), cell(r['source']), r['sha256']] for r in sec('font')]))

    add('## Vendored code\n')
    add('three.js, MIT licence, Copyright 2010-2024 three.js authors. The files are the ones in the npm package `three`\n'
        '0.170.0, unchanged.\n')
    add(table(['File', 'What', 'Source: npm package and file', 'sha256'], [[f(r['file']), cell(r['what']), cell(r['source']), r['sha256']] for r in sec('code')]))

    add('## Lists\n')
    add(table(['File', 'What'], [[f(r['file']), cell(r['what'])] for r in sec('list')]))
    return '\n'.join(o)


def problems():
    """[problem] for the credits file as it is on disk"""
    bad = []
    want = build()
    have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
    if have != want:
        bad.append('assets/CREDITS.md is out of date: run python3 tests/credits.py write')
    named = set(re.findall(r'`((?:assets|vendor)/[^`]+)`', have))
    named -= {'assets/', 'vendor/'}
    disk = {os.path.relpath(os.path.join(d, x), ROOT).replace(os.sep, '/') for top in ('assets', 'vendor') for d, _, fs in os.walk(os.path.join(ROOT, top)) for x in fs}
    bad += [f'not in assets/CREDITS.md: {x}' for x in sorted(disk - named)]
    bad += [f'named in assets/CREDITS.md but not on disk: {x}' for x in sorted(named - disk)]
    low = have.lower()
    if 'cloudfront' in low or 'user_' in low or re.search(r'https?://', have):
        bad.append('assets/CREDITS.md must not hold a storage path or a URL')
    for r in tsv('assets/credits_extra.tsv'):
        p = os.path.join(ROOT, r['file'])
        if r['section'] in ('font', 'code') and (not os.path.isfile(p) or hashlib.sha256(open(p, 'rb').read()).hexdigest() != r['sha256']):
            bad.append(f"{r['file']}: missing, or differs from its sha256 in assets/credits_extra.tsv")
    al_raw = open(os.path.join(ROOT, 'assets', 'al', 'sources.tsv'), encoding='utf-8').read().lower()
    if 'cloudfront' in al_raw or 'user_' in al_raw or re.search(r'https?://', al_raw):
        bad.append('assets/al/sources.tsv must not hold a storage path or a URL')
    for r in tsv('assets/al/sources.tsv'):
        if not r['file'].startswith('al/') or '..' in r['file'] or '\\' in r['file']:
            bad.append(f"assets/al/sources.tsv: {r['file']!r} is outside al/")
            continue
        p = os.path.join(ROOT, 'assets', r['file'])
        if not os.path.isfile(p) or hashlib.sha256(open(p, 'rb').read()).hexdigest() != r['sha256']:
            bad.append(f"assets/{r['file']}: missing, or differs from its sha256 in assets/al/sources.tsv")
    return bad


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'write':
        with open(OUT, 'w', encoding='utf-8', newline='') as fh:
            fh.write(build())
        print('wrote assets/CREDITS.md')
    elif cmd != 'check':
        sys.exit(__doc__)
    bad = problems()
    for b in bad[:40]:
        print('FAIL', b)
    print('ALL PASSED' if not bad else f'{len(bad)} FAILED')
    sys.exit(1 if bad else 0)
